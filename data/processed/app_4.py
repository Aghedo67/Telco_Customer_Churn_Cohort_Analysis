@st.cache_data
def load_cohort_matrix():
    """Rebuild retention matrix from processed files (result is cached)."""
    retail_path = PROCESSED / "online_retail_clean.parquet"
    cohort_path = PROCESSED / "customer_cohorts.csv"
    if not retail_path.exists() or not cohort_path.exists():
        return None, None

    retail = pd.read_parquet(retail_path)
    retail["InvoiceDate"]  = pd.to_datetime(retail["InvoiceDate"])
    retail["InvoiceMonth"] = retail["InvoiceDate"].dt.to_period("M")

    coh = pd.read_csv(cohort_path)
    coh["CohortMonth"] = pd.PeriodIndex(coh["CohortMonth"], freq="M")

    retail = retail.merge(coh, on="Customer ID", how="left")
    retail["CohortIndex"] = (
        (retail["InvoiceMonth"].dt.year  - retail["CohortMonth"].dt.year)  * 12
      + (retail["InvoiceMonth"].dt.month - retail["CohortMonth"].dt.month)
    )

    counts  = retail.groupby(["CohortMonth", "CohortIndex"])["Customer ID"].nunique().reset_index()
    pivot   = counts.pivot(index="CohortMonth", columns="CohortIndex", values="Customer ID")
    size    = pivot[0]
    matrix  = pivot.divide(size, axis=0)
    matrix.index = matrix.index.astype(str)
    return matrix, size


