# ── Tab 5: Revenue Impact Calculator ────────────────────────────────────────────
with tab5:
    st.subheader("Retention Campaign ROI Calculator")
    st.write("Estimate the revenue impact of a targeted retention campaign.")

    col1, col2, col3 = st.columns(3)
    with col1:
        n_targeted = st.number_input("Subscribers to target",
                                     min_value=10, max_value=2000, value=200, step=10)
    with col2:
        cost_per   = st.number_input("Campaign cost per subscriber (£)",
                                     min_value=1, max_value=100, value=10)
    with col3:
        conversion = st.slider("Estimated save rate (%)", min_value=5, max_value=60, value=20)

    if scored_df is not None:
        top_n   = scored_df.sort_values("churn_probability", ascending=False).head(int(n_targeted))
        avg_mrr = top_n["MonthlyCharges"].mean()
    else:
        avg_mrr = filtered[filtered["Churn_Binary"] == 1]["MonthlyCharges"].mean()

    saves_expected = int(n_targeted * conversion / 100)
    mrr_saved      = saves_expected * avg_mrr
    campaign_cost  = n_targeted * cost_per
    net_roi_12m    = mrr_saved * 12 - campaign_cost
    payback        = campaign_cost / (mrr_saved + 1e-8)

    st.divider()
    c1, c2, c3, c4, c5 = st.columns(5)
    c1.metric("Subscribers targeted",     f"{int(n_targeted):,}")
    c2.metric("Expected saves",           f"{saves_expected}")
    c3.metric("Monthly MRR recovered",    f"£{mrr_saved:,.0f}")
    c4.metric("Campaign cost (one-time)", f"£{campaign_cost:,.0f}")
    c5.metric("12-month net ROI",         f"£{net_roi_12m:,.0f}",
              delta="Positive" if net_roi_12m > 0 else "Negative",
              delta_color="normal" if net_roi_12m > 0 else "inverse")

    if mrr_saved > 0:
        st.info(f"Break-even point: **{payback:.1f} months** after the campaign runs.")

    st.divider()
    st.markdown("**Sensitivity — 12-month net ROI at different save rates**")
    rows = []
    for r in [0.10, 0.15, 0.20, 0.25, 0.30, 0.40]:
        s = int(n_targeted * r)
        m = s * avg_mrr
        roi = m * 12 - campaign_cost
        rows.append({
            "Save Rate": f"{r:.0%}",
            "Subscribers Saved": s,
            "Monthly MRR Recovered": f"£{m:,.0f}",
            "12-Month Net ROI": f"£{roi:,.0f}",
            "Positive?": "✅" if roi > 0 else "❌",
        })
    st.dataframe(pd.DataFrame(rows), use_container_width=True, hide_index=True)
